// Generates core/designsystem/src/main/kotlin/app/picacgmd/core/designsystem/theme/ColorTokens.kt
// from design/src/tokens.json.
//
// tokens.json carries 38 M3 roles + success/warning for every scheme, but Compose's ColorScheme also
// needs background/onBackground/surfaceTint and the secondary/tertiary *Fixed roles. Those are
// recomputed here with the same seeds and the same algorithm as design/src/gen-tokens.mjs
// (brand = SchemeVibrant, others = SchemeTonalSpot, contrast 0). Every role that exists in
// tokens.json is cross-checked against the recomputed value, so the two can never drift silently.
//
// Run through gen-color-tokens.sh (material-color-utilities' ESM build needs bundling first).
import {
  argbFromHex, hexFromArgb, Hct, SchemeTonalSpot, SchemeVibrant, MaterialDynamicColors,
} from '@material/material-color-utilities';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = process.argv[2];
if (!root) throw new Error('usage: node gen-color-tokens.bundle.mjs <repo-root>');

const tokens = JSON.parse(readFileSync(resolve(root, 'design/src/tokens.json'), 'utf8'));
const out = resolve(root, 'core/designsystem/src/main/kotlin/app/picacgmd/core/designsystem/theme/ColorTokens.kt');

// Palettes shipped in the app. `wall` is only a design-board stand-in for wallpaper colors.
const PALETTES = [
  ['brand', 'Brand', '品牌粉'],
  ['book', 'Book', '书本'],
  ['dusty', 'Dusty', '灰蓝'],
];

// Parameter order of androidx.compose.material3.lightColorScheme()/darkColorScheme().
const ROLES = [
  'primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer', 'inversePrimary',
  'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
  'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
  'background', 'onBackground', 'surface', 'onSurface', 'surfaceVariant', 'onSurfaceVariant',
  'surfaceTint', 'inverseSurface', 'inverseOnSurface',
  'error', 'onError', 'errorContainer', 'onErrorContainer',
  'outline', 'outlineVariant', 'scrim',
  'surfaceBright', 'surfaceContainer', 'surfaceContainerHigh', 'surfaceContainerHighest',
  'surfaceContainerLow', 'surfaceContainerLowest', 'surfaceDim',
  'primaryFixed', 'primaryFixedDim', 'onPrimaryFixed', 'onPrimaryFixedVariant',
  'secondaryFixed', 'secondaryFixedDim', 'onSecondaryFixed', 'onSecondaryFixedVariant',
  'tertiaryFixed', 'tertiaryFixedDim', 'onTertiaryFixed', 'onTertiaryFixedVariant',
];
const EXTENDED = [
  'success', 'onSuccess', 'successContainer', 'onSuccessContainer',
  'warning', 'onWarning', 'warningContainer', 'onWarningContainer',
];

const kColor = (hex) => `Color(0xFF${hex.replace('#', '').toUpperCase()})`;
const errors = [];
let kt = `// GENERATED by core/designsystem/scripts/gen-color-tokens.sh from design/src/tokens.json.
// Do not edit by hand: change the design tokens and re-run the script.
@file:Suppress("MagicNumber")

package app.picacgmd.core.designsystem.theme

import androidx.compose.material3.ColorScheme
import androidx.compose.material3.darkColorScheme
import androidx.compose.material3.lightColorScheme
import androidx.compose.ui.graphics.Color
`;

for (const [key, name, zh] of PALETTES) {
  const seed = tokens.seeds[key];
  for (const dark of [false, true]) {
    const tokenScheme = tokens.schemes[`${key}-${dark ? 'dark' : 'light'}`];
    const Cls = key === 'brand' ? SchemeVibrant : SchemeTonalSpot;
    const scheme = new Cls(Hct.fromInt(argbFromHex(seed)), dark, 0);
    const mode = dark ? 'Dark' : 'Light';
    const values = {};
    for (const role of ROLES) {
      const computed = hexFromArgb(MaterialDynamicColors[role].getArgb(scheme));
      const fromTokens = tokenScheme[role];
      if (fromTokens && fromTokens.toLowerCase() !== computed.toLowerCase()) {
        errors.push(`${key}-${mode}.${role}: tokens.json ${fromTokens} != computed ${computed}`);
      }
      values[role] = fromTokens ?? computed;
    }
    kt += `
/** ${zh} · ${dark ? '深色' : '浅色'} (seed ${seed}). */
val ${name}${mode}ColorScheme: ColorScheme = ${dark ? 'darkColorScheme' : 'lightColorScheme'}(
${ROLES.map((r) => `    ${r} = ${kColor(values[r])},`).join('\n')}
)

/** Harmonized success / warning roles for ${zh} · ${dark ? '深色' : '浅色'}. */
val ${name}${mode}ExtendedColors: PikapikaExtendedColors = PikapikaExtendedColors(
${EXTENDED.map((r) => {
  if (!tokenScheme[r]) errors.push(`${key}-${mode}.${r} missing from tokens.json`);
  return `    ${r} = ${kColor(tokenScheme[r] ?? '#000000')},`;
}).join('\n')}
)
`;
  }
}

if (errors.length) {
  console.error('tokens.json and the recomputed schemes disagree:\n  ' + errors.join('\n  '));
  process.exit(1);
}
writeFileSync(out, kt);
console.log('wrote', out);
